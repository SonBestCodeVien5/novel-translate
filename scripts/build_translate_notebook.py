"""Build the portable Qwen3.5 v2 Drive batch notebook."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
NOTEBOOK = ROOT / 'notebooks/translate.ipynb'
SOURCES = ('app/__init__.py', 'app/bundles.py', 'app/real_bundles.py', 'app/real_runner.py')


def bootstrap_source():
    sources = {name: (ROOT / name).read_text(encoding='utf-8') for name in SOURCES}
    hashes = {name: hashlib.sha256(text.encode('utf-8')).hexdigest() for name, text in sources.items()}
    bundle_hash = hashlib.sha256(json.dumps(hashes, sort_keys=True, separators=(',', ':')).encode()).hexdigest()
    return ("# Generated by scripts/build_translate_notebook.py; edit sources instead.\n"
            "from pathlib import Path\nimport hashlib, json, sys\n"
            f"SOURCES = {sources!r}\nSOURCE_HASHES = {hashes!r}\nSOURCE_BUNDLE_HASH = {bundle_hash!r}\n"
            "REPO = Path('/content/novel-translate-code')\n"
            "_loaded = globals().get('NOVEL_TRANSLATE_SOURCE_BUNDLE_HASH')\n"
            "if _loaded not in (None, SOURCE_BUNDLE_HASH): raise RuntimeError('Runner source changed; restart this kernel before continuing.')\n"
            "if _loaded is None and ('app.real_runner' in sys.modules or globals().get('model') is not None): raise RuntimeError('Runner is already loaded without a matching source guard; restart this kernel.')\n"
            "for name, source in SOURCES.items():\n"
            "    raw = source.encode('utf-8')\n"
            "    if hashlib.sha256(raw).hexdigest() != SOURCE_HASHES[name]: raise RuntimeError('Embedded source checksum mismatch.')\n"
            "    path = REPO / name\n"
            "    if _loaded is None:\n"
            "        path.parent.mkdir(parents=True, exist_ok=True)\n"
            "        path.write_bytes(raw)\n"
            "    elif not path.is_file() or hashlib.sha256(path.read_bytes()).hexdigest() != SOURCE_HASHES[name]:\n"
            "        raise RuntimeError('Runner files differ from loaded code; restart this kernel.')\n"
            "globals()['NOVEL_TRANSLATE_SOURCE_BUNDLE_HASH'] = SOURCE_BUNDLE_HASH\n")


def build():
    cells = [
        {'cell_type': 'markdown', 'metadata': {}, 'source': ['# Batch dịch Qwen3.5 (v2)\n',
            'Chạy trên Colab GPU. Sao chép manifest do app xuất vào `MyDrive/novel-batch/<job>/manifest.json`; sửa hai đường dẫn bên dưới cho cùng job. Mỗi chunk được ghi atomically để lần chạy lại cùng manifest tiếp tục checkpoint còn thiếu. Notebook chỉ xử lý file, không mở SQLite.']},
        {'cell_type': 'code', 'execution_count': None, 'metadata': {'translate_bootstrap': True}, 'outputs': [], 'source': bootstrap_source().splitlines(keepends=True)},
        {'cell_type': 'code', 'execution_count': None, 'metadata': {}, 'outputs': [], 'source': [
            'from importlib.metadata import PackageNotFoundError, version\n',
            'import torch\n',
            "PINS = {'transformers': '5.3.0', 'accelerate': '1.11.0', 'bitsandbytes': '0.48.2'}\n",
            'missing = []\n',
            'for package, expected in PINS.items():\n',
            '    try: actual = version(package)\n',
            '    except PackageNotFoundError: actual = None\n',
            '    if actual != expected: missing.append(package + "==" + expected)\n',
            "if missing: raise RuntimeError('Install the pinned packages, then restart: pip install ' + ' '.join(missing))\n",
            "if not torch.cuda.is_available(): raise RuntimeError('Select an existing Colab GPU runtime before continuing.')\n"]},
        {'cell_type': 'code', 'execution_count': None, 'metadata': {}, 'outputs': [], 'source': [
            'from google.colab import drive\n', 'drive.mount("/content/drive")\n',
            'from pathlib import Path\n', 'import sys\n', 'sys.path.insert(0, str(REPO))\n',
            "MANIFEST = Path('/content/drive/MyDrive/novel-batch/<job>/manifest.json')\n",
            "OUTPUT = Path('/content/drive/MyDrive/novel-batch/<job>/results')\n",
            "assert '<job>' not in str(MANIFEST) and '<job>' not in str(OUTPUT), 'Edit MANIFEST and OUTPUT with the job folder name.'\n",
            'LIMIT = None  # Set a positive integer to limit newly generated chunks.\n',
            'from app.real_runner import main\n',
            "RUN_ARGS = [str(MANIFEST), str(OUTPUT)] + (['--limit', str(LIMIT)] if LIMIT is not None else [])\n",
            'main(RUN_ARGS)\n']},
    ]
    return {'cells': cells, 'metadata': {'kernelspec': {'display_name': 'Python 3', 'language': 'python', 'name': 'python3'},
            'language_info': {'name': 'python'}}, 'nbformat': 4, 'nbformat_minor': 5}


def main():
    NOTEBOOK.write_text(json.dumps(build(), ensure_ascii=False, indent=1) + '\n', encoding='utf-8')


if __name__ == '__main__':
    main()
