"""Refresh embedded P0 code in the portable notebook; no corpus or credentials."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
NOTEBOOK = ROOT / 'notebooks/p0_benchmark.ipynb'
SOURCES = ('app/__init__.py', 'app/bundles.py', 'benchmarks/p0/runner.py')


def bootstrap_source():
    sources = {name: (ROOT / name).read_text(encoding='utf-8') for name in SOURCES}
    hashes = {name: hashlib.sha256(text.encode('utf-8')).hexdigest() for name, text in sources.items()}
    return ("# Generated by benchmarks/p0/build_notebook.py; edit the source files instead.\n"
            "from pathlib import Path\nimport hashlib\n"
            f"SOURCES = {sources!r}\nSOURCE_HASHES = {hashes!r}\n"
            "REPO = Path('/content/p0-code')\n"
            "for name, source in SOURCES.items():\n"
            "    raw = source.encode('utf-8')\n"
            "    assert hashlib.sha256(raw).hexdigest() == SOURCE_HASHES[name], 'Embedded source checksum mismatch'\n"
            "    path = REPO / name\n"
            "    path.parent.mkdir(parents=True, exist_ok=True)\n"
            "    path.write_bytes(raw)\n"
            "    assert path.read_bytes() == raw, 'Bootstrap readback mismatch'\n")


def refresh(notebook):
    for cell in notebook['cells']:
        if cell.get('metadata', {}).get('p0_bootstrap'):
            cell['source'] = bootstrap_source().splitlines(keepends=True)
            cell['outputs'], cell['execution_count'] = [], None
            return notebook
    raise ValueError('Notebook is missing the p0_bootstrap cell.')


if __name__ == '__main__':
    notebook = refresh(json.loads(NOTEBOOK.read_text(encoding='utf-8')))
    NOTEBOOK.write_text(json.dumps(notebook, ensure_ascii=False, indent=1) + '\n', encoding='utf-8')
